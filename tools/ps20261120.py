# -*- coding: utf-8 -*-
"""单件 2026-11-20：耀静 20508564 SR 护栏门（韩国）机架 851185079 的四件钣金，按总图装配核对。

来源：江波 10 月发的项目包 图纸\\8511850xx_0_0x.pdf（扫描件），总图 851185079_0_02.pdf（V.02）。
材料：零件图 1.0332-DD11/Q235B 3mm；总图明细栏 U 梁写「BL.2X25X63X80」，但零件图截面 3±0.16、零件图重量、
总图总重 28.32 kg 都是 3mm，按 3mm 出（README 写明）。BD 用 Q235B 表 5；侧墙中间 30° 折弯 bd_angle(K 由 BD5 反算)。

截面统一 U 25 / 63 / 80（外形）。展开坐标：x 沿长度，y=0 是 25 边自由边；
  25 边上距底面外侧 h 的点 y = 25 − h，80 边 y = 78 + h；红线 22.5 / 80.5，底面平直段 26.2 ~ 76.8（=50.6，图上 6.2 / 50.6）。

焊接螺柱 M8×35（总图 6，14 个，螺柱焊不开孔）：零件图展开图上只有小点，总图 V.01 又在上下梁中间加了 ±100 两个，
按总图画打标十字（图层 5、黄色、实线）：下梁 7、上梁 5、两侧墙各 1。
"""
import math
from sheetlib import bd_angle

T = 3
MARK = dict(layer='5', color=2)
TAN15, TAN30 = math.tan(math.radians(15)), math.tan(math.radians(30))
Y25 = lambda h: 25 - h                 # 25 边
Y80 = lambda h: 78 + h                 # 80 边
R1, R2 = 22.5, 80.5                    # 两条纵向折弯红线
WEB0, WEB1 = 26.2, 76.8                # 底面平直段
STUD_H = 57                            # 螺柱在 80 边上距底面外侧（零件图前视 56.9、展开图距自由边 23.5）


def _mark(p, x, y, s=3):
    p.line(x - s, y, x + s, y, **MARK).line(x, y - s, x, y + s, **MARK)


def _bends(p, x0, x1, w):
    p.bend(x0, R1, x1, R1, w).bend(x0, R2, x1, R2, w)


def register(C):
    C.mat = 'Q235B'
    w = C.bd(T)                                            # 5

    # ------------------------------------------------------------------ 851185047 U型梁(下) 2990
    @C.part('851185047')
    def _(q):
        L = 2990
        # 两头 17 内两边都只高 20；80 边 135°(45°) 斜升到 80（到 77），25 边 45° 升到 25（到 22）
        pts = [(22, 0), (L - 22, 0), (L - 17, Y25(20)), (L, Y25(20)), (L, Y80(20)), (L - 17, Y80(20)),
               (L - 77, Y80(80)), (77, Y80(80)), (17, Y80(20)), (0, Y80(20)), (0, Y25(20)), (17, Y25(20))]
        p = C.Piece().poly(pts)
        _bends(p, 0, L, w)
        # 螺柱：总图下梁距机架边 98 起每 700 + 中间 ±100；梁在机架里两头各让 3
        for X in (98, 798, 1398, 1498, 1598, 2198, 2898):
            _mark(p, X - 3, Y80(STUD_H))
        return [(C.lab(T, q), p)]

    # ------------------------------------------------------------------ 851185044 U型梁(上) 2490
    @C.part('851185044')
    def _(q):
        L = 2490
        a80 = 3 + (80 - 8) * TAN30                          # 44.57：腿端高 8、与端面成 30° 斜升
        a25 = 3 + (25 - 8) * TAN30                          # 12.81
        # 两头：底面平直段到端头，折弯区 + 两边各缩 3（图上 3 / 6.2）
        pts = [(a25, 0), (L - a25, 0), (L - 3, Y25(8)), (L - 3, WEB0), (L, WEB0), (L, WEB1), (L - 3, WEB1),
               (L - 3, Y80(8)), (L - a80, Y80(80)), (a80, Y80(80)), (3, Y80(8)), (3, WEB1), (0, WEB1),
               (0, WEB0), (3, WEB0), (3, Y25(8))]
        p = C.Piece().poly(pts)
        _bends(p, 3, L - 3, w)
        # 螺柱：总图上梁距机架边 398 / 1398 / 1498 / 1598 / 2598，上梁在 2996 机架里居中（各让 253）
        for X in (398, 1398, 1498, 1598, 2598):
            _mark(p, X - 253, Y80(STUD_H))
        return [(C.lab(T, q), p)]

    # ------------------------------------------------------------------ 侧墙 851185054(右) / 055(左，镜像)
    K = (2 * 2 * T - w) / (math.pi / 2 * T) - 1             # 由 BD5、R=t 反算 K ≈ 0.485
    BD30 = bd_angle(T, 30, K)                               # 0.88
    A = 620                                                 # 水平段：端头到底面外侧交点
    MB = 502.0                                              # 斜段底面外侧长：054 总长 1052.77 / 055 1055.37 反算一致
    XB = A - BD30                                           # 斜段起点在展开图上的 x
    XE = XB + MB                                            # 展开总长 ≈ 1121.1（客户展开 1121.54，K 不同）
    G = 1.93 / 2 / math.cos(math.radians(15))               # 两腿对缝间隙一半（图 Y：1.93）
    b80 = XE - 3 - (80 - 8) * TAN30                         # 右端同上梁：缩 3、高 8、30°
    b25 = XE - 3 - (25 - 8) * TAN30

    def side(q):
        ya = lambda h: A - G - h * TAN15                    # 水平段腿的斜接边
        yb = lambda h: XB + G + h * TAN15                   # 斜段腿的斜接边
        hw = WEB1 - Y80(0)                                  # = −1.2：V 口往下延到底面平直段边
        pts = [
            (25, 0), (ya(25), 0), (ya(hw), WEB0), (yb(hw), WEB0), (yb(25), 0), (b25, 0),
            (XE - 3, Y25(8)), (XE - 3, WEB0), (XE, WEB0), (XE, WEB1), (XE - 3, WEB1), (XE - 3, Y80(8)),
            (b80, Y80(80)), (yb(80), Y80(80)), (yb(hw), WEB1), (ya(hw), WEB1), (ya(80), Y80(80)),
            (80, Y80(80)), (20, Y80(20)),
            # 左端：底面带 63 宽舌 19 长（端角 R6.2），舌与腿之间 1 宽、6.2 深的缝（图 Z）
            (20, WEB1), (19, WEB1), (19, 83), (6.2, 83), (0, 76.8), (0, 26.2), (6.2, 20), (19, 20),
            (19, WEB0), (20, WEB0), (20, Y25(20))]
        b = math.tan(math.radians(90) / 4)
        bul = {(6.2, 83): b, (0, 26.2): b}                  # 端角圆弧：(6.2,83)→(0,76.8)、(0,26.2)→(6.2,20)
        p = C.Piece().poly([(x, y, bul.get((x, y), 0)) for x, y in pts])
        p.bend(20, R1, ya(hw) - 0.01, R1, w).bend(yb(hw) + 0.01, R1, XE - 3, R1, w)
        p.bend(20, R2, ya(hw) - 0.01, R2, w).bend(yb(hw) + 0.01, R2, XE - 3, R2, w)
        p.bend(A - BD30 / 2, WEB0, A - BD30 / 2, WEB1, w, red_only=True)   # 底面 30° 折弯
        # 焊接螺母 M8（总图 5，每侧 5 个）：Φ10.5，底面 100 / 550 居中，25 边 100 / 450 / 550 距底面 14
        for x in (100, 550):
            p.circle(x, (R1 + R2) / 2, 10.5)
        for x in (100, 450, 550):
            p.circle(x, Y25(14), 10.5)
            # 螺母处折弯区 U 形切缝：缝宽 1.5、外 18 内 15，开口朝 25 边（图 Y）
            p.poly([(x - 9, 18.3), (x - 9, 26.7), (x + 9, 26.7), (x + 9, 18.3), (x + 7.5, 18.3),
                    (x + 7.5, 25.2), (x - 7.5, 25.2), (x - 7.5, 18.3)])
        _mark(p, 552, Y80(47))                              # 螺柱：展开图上的点（距自由边约 33）
        return p

    C.part('851185054')(lambda q: [(C.lab(T, q), side(q))])
    C.part('851185055')(lambda q: [(C.lab(T, q), side(q).mirrored())])
