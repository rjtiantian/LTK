    # ================================================================ 机身板：主板取视图 + 底边折 L 翼
    def body(fname, region, t, L, x0, x1, yc, r, holes):
        """region 视图左下角 = 主板外面（y=0）；y < yc 的折弯区线丢掉，翼外形 L、自由角 R r，holes = 翼上孔 [(x, 距翼外形 s, 直径)]"""
        w = C.bd(t)
        p = C.plate('%s.idw.dxf' % fname, region,
                    drop=lambda k, i: k == 'LINE' and max(i['a'][1], i['b'][1]) < yc + 0.05)
        p = p.moved(0, -w / 2)
        y0 = yc - w / 2
        yf = -(L - w / 2)
        fl = fillet_path([(x0, y0, 0), (x0, yf, r), (x1, yf, r), (x1, y0, 0)], False)
        p.poly(fl, False)
        p.bend(x0, 0, x1, 0, w)
        for x, s, d in holes:
            p.circle(x, -(s - w / 2), d)
        return p

