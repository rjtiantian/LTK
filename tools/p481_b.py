"""NO.481 下料件（B 批，14 行）：3420101A00 框架、3420104A00 / 3420163A00 护罩、3420161A00 / 162A00 安全门、
3420207A 框架、3420210A / 211A 支撑板、3420901A / 902A / 954A 机身板、3421101A~103A 安装板。
外形尺寸法：展开长 = 各段外形和 − 折弯数 × BD；面上特征距外形交点 s → 红线 ± (s − BD/2)。
方管只出长度标签 + 截面；孔、斜接、插接舌在 481/管材STEP/make_tubes_b.py 出的 STEP 里。"""
import math
from sheetlib import fillet_path


def register(C):
    def outline(p, verts):
        """同 Piece.outline，但去掉圆角切点与相邻顶点重合产生的零长线段"""
        verts = [tuple(v) + (0.0,) * (3 - len(v)) for v in verts]
        pts = fillet_path(verts, True)
        out = []
        for i, pt in enumerate(pts):
            nx = pts[(i + 1) % len(pts)]
            if abs(pt[0] - nx[0]) < 1e-9 and abs(pt[1] - nx[1]) < 1e-9:
                continue
            out.append(pt)
        return p.poly(out, True)

    def blg(deg):
        """圆弧 bulge：deg > 0 逆时针、< 0 顺时针"""
        return math.tan(math.radians(deg) / 4)

    # ================================================================ 3420101A00 框架（方管焊接）
