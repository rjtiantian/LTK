        leg = C.Piece().rect(0, 0, 50, 50, 2).tap(25, 25, 'M16')
        out = [(C.lab(10, 5 * q), leg)]
        for L, n in [(1800, 5), (1700, 1), (1250, 1), (1200, 1), (1000, 1), (900, 5), (700, 5), (550, 1), (450, 3)]:
            out.append((C.lab(L, n * q), C.tube_rect(50, 50, 2.5)))
        return out

