    # ================================================================ 护罩：多段 L 形折弯件焊接（3mm，BD 5）
    T3, W3 = 3, C.bd(3)
    H3 = 30 - W3 / 2                                    # 30 外形 → 距红线 27.5

    def guard_u(strips, flange_h, plate_h):
        """U 形长条：端片 30 ─折─ 段0 ─折─ 段1 ─折─ 段2 ─折─ 端片 30，整条沿 v=0 再折出 L 形翻边。
        strips = 三段外形长；flange_h / plate_h = [(段号, 距该段起始外形的 d)]（孔 Φ8.5 在翻边、Φ6.5 在板面，都距外形 20）。
        图纸：中间两角翻边 45° 斜接（缝 0.5）、三折相碰处 6×6 方口；两头翻边止于距端面 3.35、端片距翻边外面 3.35 起；
        板面内角 R20，板面到外形 50 处是与直段的对接缝（不倒圆）。"""
        U = [H3]
        for L in strips:
            U.append(U[-1] + L - W3)
        u0, u1, u2, u3 = U
        S = 3.854                                       # 斜接起点（图纸 6.354 − 2.5）
        v = [(u0 - H3, 0.854), (u0 - 3.5, 0.854), (u0 - 3.5, 3.5), (u0 + 0.852, 3.5), (u0 + 0.852, -H3)]
        for u in (u1, u2):
            v += [(u - S - 24, -H3), (u - S, -3.5), (u - S, 3.5), (u + S, 3.5), (u + S, -3.5), (u + S + 24, -H3)]
        v += [(u3 - 0.852, -H3), (u3 - 0.852, 3.5), (u3 + 3.5, 3.5), (u3 + 3.5, 0.854), (u3 + H3, 0.854), (u3 + H3, 47.5)]
        for ua, ub in ((u3, u2), (u2, u1), (u1, u0)):   # 上边：对接缝 v=47.5 → R20 → 内边 v=27.5 → R20
            v += [(ua - H3, 47.5), (ua - H3, 27.5, 20), (ub + H3, 27.5, 20), (ub + H3, 47.5)]
        v += [(u0 - H3, 47.5)]
        p = outline(C.Piece(), v)
        for u in U:
            p.bend(u, 3.5, u, 47.5, W3)
        p.bend(u0 + 0.852, 0, u1 - S, 0, W3).bend(u1 + S, 0, u2 - S, 0, W3).bend(u2 + S, 0, u3 - 0.852, 0, W3)
        for k, d in flange_h:
            p.circle(U[k] + d - W3 / 2, -17.5, 8.5)
        for k, d in plate_h:
            p.circle(U[k] + d - W3 / 2, 17.5, 6.5)
        return p

    def guard_l(up=(), down=()):
        """直段 L 30×30，长 649.8（两头对接 U 形件的 50 处，缝 0.1）：up / down = 两翼 Φ6.5 距件端位置（距外形 20）"""
        p = C.Piece().rect(0, -H3, 649.8, H3)
        p.bend(0, 0, 649.8, 0, W3)
        for s in up:
            p.circle(s, 17.5, 6.5)
        for s in down:
            p.circle(s, -17.5, 6.5)
        return p

    def guard_angle(LA, LB):
        """护罩支撑 L 30×30：翼 A 长 LA（两端 27 伸出段高 27、外角 R5，根部让位缝：图纸 0.5×3 方缝，这里收成 V 形尖到折弯区外），翼 B 长 LB = LA − 54"""
        x = (LA - LB) / 2
        p = outline(C.Piece(), [(0, 0), (LA, 0), (LA, 27, 5), (LA - x + 0.5, 27), (LA - x, 24),
                                (LA - x, H3 * 2), (x, H3 * 2), (x, 24), (x - 0.5, 27), (0, 27, 5)])
        p.bend(x, H3, LA - x, H3, W3)
        return p

    @C.part('3420104A00')
    def _(q):
        # 明细栏：A01 护罩 ×1（焊接件，拆 U 形 ×2 + 直段 ×4）+ A02 ×2 + A03 ×1
        # U 形：左腿 690 ─ 顶 1260 ─ 右腿 960，展开 2950；前后两件互为镜像（A 面朝外，左右腿不等长）
        u = guard_u([690, 1260, 960],
                    [(0, 50), (0, 345), (0, 640), (1, 50), (1, 380), (1, 710), (1, 800), (1, 1210), (2, 50), (2, 480), (2, 910)],
                    [(0, 130), (0, 560), (1, 130), (1, 630), (1, 1130), (2, 180), (2, 505), (2, 830)])
        top = guard_l(up=(79.9, 569.9), down=(99.9, 549.9))      # 顶部两侧：侧面翼 x=130/620、顶面翼 y=150/600
        bot = guard_l(up=(79.9, 569.9))                          # 底部两侧：只有侧面翼 2 孔，底面翼无孔
        return [(C.lab(T3, q), u), (C.lab(T3, q), u.mirrored()), (C.lab(T3, 2 * q), top), (C.lab(T3, 2 * q), bot),
                (C.lab(T3, 2 * q), guard_angle(1254, 1200)), (C.lab(T3, q), guard_angle(744, 690))]

    @C.part('3420163A00')
    def _(q):
        # 明细栏：A01 护罩 ×1（焊接件，拆 U 形 ×2 + 直段 ×4）+ A02 ×2
        # U 形：顶 600 ─ 侧 510 ─ 底 600（右端开口），展开 1750；对称，前后两件相同
        u = guard_u([600, 510, 600],
                    [(0, 50), (0, 300), (0, 550), (1, 50), (1, 255), (1, 460), (2, 50), (2, 300), (2, 550)],
                    [(0, 130), (0, 470), (1, 130), (1, 380), (2, 130), (2, 470)])
        left = guard_l(up=(99.9, 549.9), down=(79.9, 569.9))     # 左侧上下：侧面翼 x=150/600、顶(底)面翼 y=130/620
        right = guard_l(down=(79.9, 569.9))                      # 右侧上下：只有顶(底)面翼 2 孔
