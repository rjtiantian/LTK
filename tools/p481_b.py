        p.bend(xb, 0, xb, W, w)
        for s, y in holes_plate:                        # s = 距翼外面（平面上）
            p.tap(xb + s - w / 2, y, 'M8')
        for y in holes_flange:
            p.circle(15, y, 9)                          # Φ9 “-3 深”= 通孔，距翼自由边 15
        return p

