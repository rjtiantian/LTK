    # ================================================================ 3421101A~103A 安装板（3mm）
    def plate_l(W, holes_plate, holes_flange, r):
        """L 形：平面 203 + 翼 31，展开 229；翼自由端 x=0"""
        w = C.bd(3)
        xb = 31 - w / 2                                 # 红线 28.5
