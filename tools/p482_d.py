def _hist(code, pick=None, i=0):
    res = histlib.hist_pieces(code, pick)
    assert res, '历史中找不到 %s %s' % (code, pick)
    return res[i][1].normalized()


def _K(t, R, w):
    """由 90° 的 BD 表反算 K，非 90° 折弯与表一致（同 p477_b）"""
    return (2 * (R + t) - w) / (math.pi / 2) / t - R / t


def _ba(deg, t, R, K):
    """折弯区中性层弧长"""
    return math.radians(deg) * (R + K * t)


def _blue(p, x0, y0, x1, y1):
    p.poly([(x0, y0), (x1, y1)], False, BEND, linetype='CENTER', color=5)


