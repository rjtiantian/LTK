        # 2-Φ8.5 距底 30、中心距 40；四角 R5（未注圆角 R5）。展开 55.79。
        # 历史 NO.455 同号为 70×56、折弯线在 40（按投影高取），与新图按 K 展开差 0.2，按新图重画。
        t = 5; R = 5; K = _K(t, R, C.bd(t))
        a = _ba(10.62, t, R, K)
        y1 = 39.071; L = y1 + a + 15.35
        p = C.Piece().rect(0, 0, 70, L, 5)
        p.bend(0, y1 + a / 2, 70, y1 + a / 2, 0, red_only=True)
        p.circle(15, 30, 8.5).circle(55, 30, 8.5)
        return [(C.lab(t, q), p)]

