def _K(t, R, w):
    """由 90° 的 BD 表反算 K"""
    return (2 * (R + t) - w) / (math.pi / 2) / t - R / t


def _ba(deg, t, R, K):
    """折弯区中性层弧长"""
    return math.radians(deg) * (R + K * t)


def _d(deg, t, R, K):
    """非 90° 折弯的外形尺寸扣除"""
    return 2 * (R + t) * math.tan(math.radians(deg) / 2) - _ba(deg, t, R, K)


def _blue(p, x0, y0, x1, y1):
    p.poly([(x0, y0), (x1, y1)], False, BEND, linetype='CENTER', color=5)


