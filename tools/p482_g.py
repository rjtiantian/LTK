# ====================================================================== 管材 STEP（交管材激光）
def make_tubes():
    """A40×60 立柱：一端 45° 斜切（长边 L、短边 L−40），4-Φ9 过两面 40 宽壁（距底 28 / 55，1611203A00 无孔）；
    40×40 横撑平头。圆角按 SKILL：SUS304 外 R = 1.2t、内 R = 外 − t（明细栏 R 不用）。
    横撑 45° 菱形放置，没有贴立柱外侧的管壁，不加插接舌（见 notes）。"""
    from frame3d import tube, keep, cut, cyl, volume, valid, bbox
    from tube_step import write
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    out = os.path.join(root, '482', '管材STEP')
    os.makedirs(out, exist_ok=True)
    S2 = math.sqrt(0.5)

    def post(t, L, holes=True):
        # 截面 x 0~40、y 0~60，z 0~L；x=40 一侧长 L，x=0 一侧长 L-40
        s = tube('z', (0, 0, 0), (40, 60, L), t)
        s = keep(s, (0, 0, L - 40), (S2, 0, -S2))
        if holes:
            for z in (28, 55):
                s = cut(s, cyl('y', (20, 0, z), 9, -1, 61))
        return s

    def rail(L):
        return tube('z', (0, 0, 0), (40, 40, L), 2)

    items = [
        ('1610621A00-支撑腿-方管40x60x3-L323-45-6件', post(3, 323)),
        ('1610621A00-支撑腿-方管40x60x2-L323-45-6件', post(2, 323)),
        ('1610621A00-支撑腿-方管40x40x2-L611-6件', rail(611)),
        ('1610707A00-支撑腿-方管40x60x3-L318-45-2件', post(3, 318)),
        ('1610707A00-支撑腿-方管40x60x2-L302-45-2件', post(2, 302)),
        ('1610707A00-支撑腿-方管40x40x2-L611-2件', rail(611)),
        ('1611203A00-支撑腿-方管40x60x2-L288-45-4件', post(2, 288, holes=False)),
        ('1611203A00-支撑腿-方管40x40x2-L536-2件', rail(536)),
    ]
    for name, s in items:
        write(s, os.path.join(out, name + '.step'), name.encode('ascii', 'ignore').decode() or 'tube')
        print(name, 'valid', valid(s), 'bbox', bbox(s), 'kg %.3f' % (volume(s) * 7.93e-6))


if __name__ == '__main__':
    make_tubes()
