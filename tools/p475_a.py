        r = 50 - w / 2                                 # 红线：立边自由端 u=0，外形 50
        X = lambda s: r + (s - w / 2)                  # 平面(70)上距外角 s
        p = C.Piece()
        n1, n2 = X(29.5), X(54.5)                      # 顶部两个 U 形缺口（宽10，深5+R5）
        _prof(p, [(0, 0, 2), (X(70), 0, 2), (X(70), 55, 2),
                  (n2 + 5, 55, 2), (n2 + 5, 50, 0, -1), (n2 - 5, 50), (n2 - 5, 55, 2),
                  (n1 + 5, 55, 2), (n1 + 5, 50, 0, -1), (n1 - 5, 50), (n1 - 5, 55, 2),
                  (0, 55, 2)])
        p.bend(r, 0, r, 55, w)
        p.slot(X(42), 38, X(42), 50, 5.5)              # 腰孔 5.5，38~50
        p.rect(X(17), 16, X(62), 31, 2)                # 方孔 45x15 R2
        p.circle(X(25), 8, 7).circle(X(55), 8, 7)      # 2-Φ7
        for s in (20, 36):                             # 立边 4-M4：距外角 20/36，高 21/42
            for y in (21, 42):
                p.tap(r - (s - w / 2), y, 'M4')
        return [(C.lab(t, q), p)]

