    C.mirror('0160403A', '0160402A')                     # 0160402A 图纸镜像表：对称制作

    # ------------------------------------------------------------ 挡板（2mm 托盘形）：底板 + 两端翻边25 + 后立板70(局部)
    def tray(L, D, backL, backR, s0, s1, s_step, slots, sd, t=2):
        def f(q):
            w = C.bd(t)
            xr0, xr1 = 25 - w / 2, 25 - w / 2 + L - w        # 左右翻边红线
            X = lambda s: xr0 + (s - w / 2)                  # 底板上距左外形 s
            Lf = xr1 + 25 - w / 2
            ry = D - w / 2                                   # 后立板红线
            Y = lambda h: ry + (h - w / 2)                   # 立板高 h（自底面外形起）
            a, b, c = X(s0), X(s1), X(s_step)
            v = [(0, 0, 5), (Lf, 0, 5), (Lf, backR, 5), (b, backR, 5), (b, Y(20), 5), (c, Y(20), 5), (c, Y(70), 5)]
            for sc in sorted(slots, reverse=True):
                x = X(sc)
                v += [(x + 4.25, Y(70), 5), (x + 4.25, Y(70 - sd), 0, -1), (x - 4.25, Y(70 - sd)), (x - 4.25, Y(70), 5)]
            v += [(a, Y(70), 5), (a, backL), (0, backL, 5)]
            p = C.Piece()
            _prof(p, v)
            p.bend(xr0, 0, xr0, backL, w).bend(xr1, 0, xr1, backR, w).bend(a, ry, b, ry, w)
            return [(C.lab(t, q), p)]
        return f

    C.PARTS['0160404A'] = tray(427, 220, 216, 205, 101, 397, 287, (136, 266), 29)
