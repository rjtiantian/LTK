    # ------------------------------------------------------------ 型材连接件：3mm U 形槽(腹板外形 86，两侧板外形 55，长 1155)
    # 腹板只在 40~1005 段，两端为侧板伸出的耳板；腹板端部释放口 6 深（图纸详图 A/B 为 1 宽）。
