        v = []
        if leg:
            v += [(0, D1(305), 5), (39, D1(305), 5), (39, D1(255), 0, -0.41421356), (239, D1(55))]
        else:
            v += [(0, 0, 5)]
        g = 1.0                                           # 释放口宽（按图纸 1 宽，QA 会报为间距 1mm 的平行线，属正常）
