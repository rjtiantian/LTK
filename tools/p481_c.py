"""NO.481 零件展开（第 C 批）：3420258A00~3420268A、3420349A/350A、3420352A、3420604A00、3420605A00。
外形尺寸法：展开长 = 各边外形之和 − 折弯数 × BD；面上特征距折弯外形交点 s → 红线 ± (s − BD/2)。"""
