    def hole_slot_v(p, x, y0, y1, w, yc, d):
        """竖腰孔（宽 w，两端圆心 y0 / y1），中间 yc 处叠一个比腰宽略大的 Φd 孔（图上 Φ6.6 叠 6.5 宽腰）"""
        a = math.asin(w / d)                               # 腰边与圆的交点相对圆心的夹角（从竖直方向量）
        dy = d / 2 * math.cos(a)
        b = math.tan((math.pi - 2 * a) / 4)
        hw = w / 2
        return p.poly([(x + hw, y0, 0), (x + hw, yc - dy, b), (x + hw, yc + dy, 0), (x + hw, y1, 1),
                       (x - hw, y1, 0), (x - hw, yc + dy, b), (x - hw, yc - dy, 0), (x - hw, y0, 1)], True)

    def sym_path(left, W):
        """左半边轮廓（从底到顶，顺时针走，(x, y, 到下一点的 bulge)）左右对称补全成闭合轮廓"""
        right = []
        n = len(left)
        for i in range(n - 1, -1, -1):
            x, y, _ = left[i]
            b = left[i - 1][2] if i > 0 else 0.0
            right.append((W - x, y, b))
        return list(left) + right

