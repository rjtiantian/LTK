        tq = (Pz + 0 - (zt - 3 * n[1])) / (-u[1])         # 从 P 沿 u 到 Q 的距离
        Q = (Px + tq * u[0], Pz + tq * u[1])
        T3 = (Q[0] + 3 * n[0], zt)
        Ta = (Px - 0.7 * n[0], Pz - 0.7 * n[1])           # 斜壁切线（红线外 1.85）上的顶端
        Tb = (Q[0] - 0.7 * n[0], Q[1] - 0.7 * n[1])
        top = zt + AHEM + HEM
        left = low + [(Ta[0], Ta[1], 0), (Tb[0], Tb[1], 0), (T3[0], T3[1], 0), (3.0, zt, 0), (3.0, top, 0)]
