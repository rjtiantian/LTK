"""NO.475 下料件（B 组）：
A 类 —— 历史有同号人工下料图：先用 histlib 取历史人工件，与新图纸逐项核对（板厚、外形/展开、孔、折弯线、组件用量），
          一致则复用历史几何（标签件数按本单重算，折弯线按规则补齐）；不一致以新图纸为准重画。
B 类 —— 新件，按图纸展开。
"""
import os, sys
