import histlib
from sheetlib import BEND


def _hist(code, pick, i):
    """历史人工展开件（左下角归零）。pick 为表头中用于选定某次下料的字符串"""
    res = histlib.hist_pieces(code, pick)
    assert res, '历史中找不到 %s %s' % (code, pick)
    return res[i][1].normalized()


def _add_blue(p, y, w):
    """历史件 y 处的 90° 折弯只有红线：保留红线，补两侧蓝线（间距 BD），范围取该红线两端"""
    xs = [q[0] for k, d, a in p.ents if a.get('layer') == BEND and k == 'LWPOLYLINE'
          for q in d[0] if abs(d[0][0][1] - y) < 0.01 and abs(d[0][-1][1] - y) < 0.01]
    assert xs, '未找到 y=%s 的折弯红线' % y
    x0, x1 = min(xs), max(xs)
    for yy in (y - w / 2, y + w / 2):
        p.poly([(x0, yy), (x1, yy)], False, BEND, linetype='CENTER', color=5)
    return p


