def _views(path, layer='可见 (ISO)'):
    """图纸中各视图（可见轮廓按包围盒合并）的区域，按面积从大到小"""
    bs = []
    for e in ezdxf.readfile(path).modelspace():
        if e.dxf.layer != layer or e.dxftype() not in ('LINE', 'ARC', 'CIRCLE', 'LWPOLYLINE', 'ELLIPSE'):
            continue
        b = _bbox.extents([e])
        if b.has_data:
            bs.append([b.extmin.x, b.extmin.y, b.extmax.x, b.extmax.y])
    merged = True
    while merged:
        merged, out = False, []
        for b in bs:
            for o in out:
                if b[0] <= o[2] + 1 and o[0] <= b[2] + 1 and b[1] <= o[3] + 1 and o[1] <= b[3] + 1:
                    o[:] = [min(o[0], b[0]), min(o[1], b[1]), max(o[2], b[2]), max(o[3], b[3])]
                    merged = True
                    break
            else:
                out.append(list(b))
        bs = out
    return sorted(bs, key=lambda b: -(b[2] - b[0]) * (b[3] - b[1]))


def _outline(p, verts):
    """同 Piece.outline，但去掉相邻重合点（槽底两个 R=半宽 的圆角正好相接）"""
    pts = []
    for q in fillet_path([tuple(v) + (0.0,) * (3 - len(v)) for v in verts]):
        if pts and math.hypot(q[0] - pts[-1][0], q[1] - pts[-1][1]) < 1e-6:
            pts[-1][2] = q[2]
            continue
        pts.append(q)
    if math.hypot(pts[0][0] - pts[-1][0], pts[0][1] - pts[-1][1]) < 1e-6:
        pts.pop()
    return p.poly(pts, True)


