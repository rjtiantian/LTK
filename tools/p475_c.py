"""NO.475：人工装箱平台组件(1600101A00/1600102A00/1600103A00) + 机身板(1600105A~1600115A)"""


def register(C):
    # ------------------------------------------------ 人工装箱平台大板（3mm C 形，台阶式）
    # 截面：长翻边 53（全长）+ 腹板 + 短翻边 28；腹板外形 503（深段）或 183（浅段），三条折弯同向 90°。
    # 展开(y 从 53 翻边自由边起)：53 折弯红线 50.5；浅段红线 228.5、翻边边 254；深段红线 548.5、翻边边 574。
    # 深/浅段交界：深段腹板边直落，浅段翻边让开 3（图纸原有避让，深到浅段折弯切点外 1.5 → y=224.5）。
    # 孔：深段 28 翻边 Φ9（距腹板外形 18 → y=564）；53 翻边 Φ11（距腹板外形 28 → y=25）。
    def platform(L, segs, h9, h11, r_left, r_right, t=3):
        w = C.bd(t)                                   # 5
        r1 = 53 - w / 2                               # 50.5
        RS = r1 + (183 - w); ES = RS + 28 - w / 2     # 228.5 / 254
        RD = r1 + (503 - w); ED = RD + 28 - w / 2     # 548.5 / 574
        yr = RS - w / 2 - 1.5                         # 224.5 释放口底
        top = lambda k: ED if k == 'D' else ES
        v = [(0, 0, 5), (L, 0, 5)]
        last = segs[-1]
        v.append((L, top(last[2]), r_right))
        for i in range(len(segs) - 1, 0, -1):
            a, b = segs[i - 1], segs[i]
            v += [(b[0], top(b[2])), (b[0], yr), (a[1], yr), (a[1], top(a[2]))]
        v.append((0, top(segs[0][2]), r_left))
        p = C.Piece().outline(v)
        p.bend(0, r1, L, r1, w)
        for x0, x1, k in segs:
            y = RD if k == 'D' else RS
            p.bend(x0, y, x1, y, w)
        for x in h9:
            p.circle(x, RD + (18 - w / 2), 9)
        for x in h11:
            p.circle(x, r1 - (28 - w / 2), 11)
        return p

    def a02():          # 1600101A02 支撑件 3mm 平板 497x50 斜边，4-Φ9
        return C.plate('1600101A00.idw_图纸_3.dxf', (122.8, 314.3, 621.8, 366.4))

    def b02():          # 1450904A02 支撑件 3mm 平板 177x50 斜边，2-Φ9
        return C.plate('1600101A00.idw_图纸_4.dxf', (39.6, 90.3, 218.6, 142.3))

    @C.part('1600101A00')
    def _(q):
        # BOM：A01 人工装箱平台 ×1、1600101A02 支撑件 ×4、1450904A02 支撑件 ×1
        a01 = platform(2100, [(0, 500, 'D'), (503, 1097, 'S'), (1100, 1600, 'D'), (1603, 2100, 'S')],
                       (28, 58, 235, 265, 442, 472, 1128, 1158, 1335, 1365, 1542, 1572), (1860, 1930), 0, 5)
        return [(C.lab(3, q), a01), (C.lab(3, 4 * q), a02()), (C.lab(3, q), b02())]

    @C.part('1600102A00')
    def _(q):
        # BOM：A01 人工装箱平台 ×1、1600101A02 支撑件 ×4、1450904A02 支撑件 ×2
        a01 = platform(2700, [(0, 497, 'S'), (500, 1000, 'D'), (1003, 1597, 'S'), (1600, 2100, 'D'),
                              (2103, 2700, 'S')],
                       (528, 558, 735, 765, 942, 972, 1628, 1658, 1835, 1865, 2042, 2072),
                       (1209, 1279, 2560, 2630), 5, 5)
        return [(C.lab(3, q), a01), (C.lab(3, 4 * q), a02()), (C.lab(3, 2 * q), b02())]

    @C.part('1600103A00')
    def _(q):
        # BOM：A01 人工装箱平台 ×1、1600101A02 支撑件 ×2、1450904A02 支撑件 ×1
        a01 = platform(1000, [(0, 500, 'D'), (503, 1000, 'S')], (28, 58, 442, 472), (721, 791), 0, 0)
        return [(C.lab(3, q), a01), (C.lab(3, 2 * q), a02()), (C.lab(3, q), b02())]

    # ------------------------------------------------ 机身板：2.5mm C 形（下翼边 25 + 腹板 H + 上翼边 F）
    # 展开 y 从下翼边自由边起：下红线 23；上红线 23+(H-4)；腹板上距下外形 h 的孔 y = 21 + h。
    # 下翼边腰孔/孔距腹板外形 15 → y = 10。坐标 x 为主视图方向（图纸长度方向，真实尺寸）。
    t = 2.5
    w = C.bd(t)                                       # 4
    R1 = 25 - w / 2                                   # 23
    yw = lambda h: R1 + (h - w / 2)                   # 腹板特征

    def body(L, H, F, start, r, left_top):
        """start: 上翼边起点 x；left_top: 左端无上翼边处腹板轮廓 [(x,h,R),...]（从 x=start 向左）"""
        R2 = R1 + (H - w)
        E2 = R2 + F - w / 2
        v = [(0, 0, r), (L, 0, r), (L, E2, r), (start, E2, r)]
        v += [(x, yw(h), rr) for x, h, rr in left_top]
        p = C.Piece().outline(v)
        p.bend(0, R1, L, R1, w)
        p.bend(start, R2, L, R2, w)
        return p

    @C.part('1600105A')
    def _(q):
        # 尾部机身板 3064：腹板 160，上翼边 18（自 x=152 起，2912 长），下翼边 25；左段腹板高 155，左上角 R5
        L = 3064
        p = body(L, 160, 18, 152, 5, [(152, 155, 0), (0, 155, 5)])
        for k in range(12):                               # 12-M5（腹板，距下外形 147）
            p.tap(289 + 250 * k, yw(147), 'M5')
        for k in range(6):                                # 12-Φ10.5（h 125 / 35）
            x = 314 + 500 * k
            p.circle(x, yw(125), 10.5).circle(x, yw(35), 10.5)
        p.circle(3039, yw(125), 10.5).circle(3039, yw(95), 10.5)       # 局部 B
        for x, h in ((116, 135), (146, 135), (171.5, 90)):            # 局部 A
            p.circle(x, yw(h), 10.5)
        p.slot(20, yw(36), 20, yw(46), 10.5).slot(20, yw(116), 20, yw(126), 10.5)
        xs = [256.5, 356.5, 406.5] + [756.5 + 500 * k + d for k in range(5) for d in (0, 100)] + [2956.5]
        for x in xs:                                      # 14 腰孔 9x(15+9)，下翼边
            p.slot(x, 10, x + 15, 10, 9)
        return [(C.lab(t, q), p)]

    @C.part('1600107A')
    def _(q):
        # 头部机身板 3000（主视图有两处打断，按尺寸建模）：腹板 160，上翼边 17.5（自 x=115 起，2885 长），
        # 下翼边 25；左段腹板高 153.75（直角）；翼边端角 R6
        L = 3000
        p = body(L, 160, 17.5, 115, 6, [(115, 153.75, 0), (0, 153.75, 0)])
        for k in range(1, 12):                            # 12-M5（h 147）
            p.tap(250 * k, yw(147), 'M5')
        p.tap(2975, yw(147), 'M5')
        for k in range(6):                                # Φ10.5（h 125 / 35）
            x = 290 + 500 * k
            p.circle(x, yw(125), 10.5).circle(x, yw(35), 10.5)
        p.circle(2975, yw(125), 10.5).circle(2975, yw(95), 10.5)       # 局部 B
        for x, h in ((230, 109), (194.7, 109), (162.7, 132.9), (162.7, 85.1)):   # 局部 A 4-Φ10.5
            p.circle(x, yw(h), 10.5)
        p.circle(110, yw(109), 50)                        # Φ50
        p.slot(20, yw(115), 20, yw(125), 11).slot(10, yw(40), 30, yw(40), 11)
        xs = [142.5 + 500 * k + d for k in range(6) for d in (0, 50, 150, 200)] + [2892.5]
        for x in xs:                                      # 25 腰孔，下翼边
            p.slot(x, 10, x + 15, 10, 9)
        return [(C.lab(t, q), p)]

    def head(xs0, r):
        """1600109A / 1600114A：3000 长，腹板 90，上翼边 17.5（自 x=50 起），下翼边 25；
        左端腹板耳片 47.5 宽、高 100（两角 R），耳片与上翼边间 2.5 宽避让口（至 h=83.75）"""
        def f(q):
            L = 3000
            p = body(L, 90, 17.5, 50, r, [(50, 83.75, 0), (47.5, 83.75, 0), (47.5, 100, r), (0, 100, r)])
            for k in range(1, 12):                        # M5（h 77）11 + 2975 + 耳片 1 = 13
                p.tap(250 * k, yw(77), 'M5')
            p.tap(2975, yw(77), 'M5').tap(10, yw(90), 'M5')
            for k in range(6):
                p.circle(250 + 500 * k, yw(20), 5.5)      # 6-Φ5.5（h 20）
                p.circle(250 + 500 * k, yw(60), 10.5)     # Φ10.5（h 60）
            p.circle(2975, yw(60), 10.5)
            for x, h in ((93.55, 76.5), (122.55, 56), (93.55, 35.5)):   # 局部 A → 共 10-Φ10.5
                p.circle(x, yw(h), 10.5)
            p.circle(167, yw(56), 11).circle(47, yw(56), 40)
            for k in range(6):                            # 18 腰孔，下翼边
                for d in (0, 50, 100):
                    x = xs0 + 500 * k + d
                    p.slot(x, 10, x + 15, 10, 9)
            p.circle(2975, 10, 10.5)                      # 下翼边 Φ10.5
            return [(C.lab(t, q), p)]
        return f

    C.PARTS['1600109A'] = head(272.5, 6)
    C.PARTS['1600114A'] = head(311.5, 5)

    C.mirror('1600106A', '1600105A')
    C.mirror('1600108A', '1600107A')
    C.mirror('1600110A', '1600109A')
    C.mirror('1600115A', '1600114A')
