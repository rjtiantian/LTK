# -*- coding: utf-8 -*-
"""单件（2026-10-17）：0160413A 光电支架、0160414A 反光板支架、5401136B 压箱板，均 SUS304 表面拉丝。"""


def register(C):
    # 光电支架 3mm U 形：左立边 50 + 底 100 + 右立边 25（外形），BD 5 → 展开 165 x 50。
    # x 从左立边顶起：红线 47.5 / 142.5；底面距左外表面 s → x = 45 + s；左立边距底外表面 z → x = 50 - z。
    @C.part('0160413A')
    def _(q):
        t = 3; w = C.bd(t)
        p = C.Piece().rect(0, 0, 165, 50, 5)                 # 两立边顶角 R5
        p.circle(45 + 60, 20, 3.5)                           # 转轴孔 Φ3.5（-3 深 = 通孔）
        p.arc_slot(105, 20, 25.4, -22.5, 22.5, 3.5)          # 45° 弧形孔 R25.4 宽 3.5，朝右立边
        for z in (40, 20):                                   # 左立边 2 条 8.5 宽腰孔，长向 10~40
            p.slot(50 - z, 10, 50 - z, 40, 8.5)
        p.bend(47.5, 0, 47.5, 50, w).bend(142.5, 0, 142.5, 50, w)
        return [(C.lab(t, q), p)]

    # 反光板支架 3mm L 形：立边 80 + 顶边 50（外形），宽 60，BD 5 → 展开 125 x 60，四角 R5。
    @C.part('0160414A')
    def _(q):
        t = 3; w = C.bd(t)
        p = C.Piece().rect(0, 0, 125, 60, 5)
        for y in (10, 50):                                   # 立边 2 条 6.5 宽腰孔，距底 10~60
            p.slot(10, y, 60, y, 6.5)
        for y in (15, 45):                                   # 顶边 2 条 8.5 宽腰孔，距立边外表面 17.5~42.5
            p.slot(75 + 17.5, y, 75 + 42.5, y, 8.5)
        p.bend(77.5, 0, 77.5, 60, w)
        return [(C.lab(t, q), p)]

    # 压箱板 4mm：底板 240 x 158（外形，前角 R10，12-Φ7），后边 90° 上折立板，立板分三片（81 / 70 / 81，缝宽 4）：
    # 两侧片外高 30、中片外高 100，顶部再向内折 30°（150°）翻边 20，翻边角 R10。
    # 画法同历史 NO.461 A 版人工展开（前边 y=0，缝底方口）；A→B：底板深 65 → 158，孔 6-Φ6.6 两排 → 12-Φ7 四排。
    # 非 90° 折弯按 K 因子（由 BD 表 4mm→6.8 反算 K≈0.464，R=4）只画红线；90° 折弯红+蓝。
    @C.part('5401136B')
    def _(q):
        t = 4; R = 4; w = C.bd(t)                            # 6.8
        m = C.math
        K = ((2 * (R + t) - w) / (m.pi / 2) - R) / t
        o30 = (R + t) * m.tan(m.radians(15))                 # 30° 外切线长 2.14
        ba90, ba30 = 2 * (R + t) - w, m.radians(30) * (R + K * t)
        r90 = 158 - w / 2                                    # 154.6
        r30a = r90 + ba90 / 2 + (30 - (R + t) - o30) + ba30 / 2      # 两侧片 30° 红线 180.59
        r30b = r90 + ba90 / 2 + (100 - (R + t) - o30) + ba30 / 2     # 中片 30° 红线 250.59
        ta, tb = r30a + ba30 / 2 + 20 - o30, r30b + ba30 / 2 + 20 - o30   # 翻边端 199.98 / 269.98
        ys = r90 - w / 2 + 25.85                             # 缝底：距底板外表面 25.85 → 177.05
        p = C.Piece().outline([(0, 0, 10), (240, 0, 10), (240, ta, 10), (159, ta, 10), (159, ys), (155, ys),
                               (155, tb, 10), (85, tb, 10), (85, ys), (81, ys), (81, ta, 10), (0, ta, 10)])
        for u in (40, 120, 200):
            for y in (10, 62.5, 87.5, 140):
                p.circle(u, y, 7)
        p.bend(0, r90, 240, r90, w)
        p.bend(0, r30a, 81, r30a, 0, red_only=True).bend(159, r30a, 240, r30a, 0, red_only=True)
        p.bend(85, r30b, 155, r30b, 0, red_only=True)
        return [(C.lab(t, q), p)]
