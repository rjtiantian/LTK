# -*- coding: utf-8 -*-
"""单件（2026-10-22 清单，13 行）：NO.451 / NO.461 / NO.462。几何均取 DWG 矢量（单件/2026-10-22/DXF，1:1）。

方管件（5363401A00 一步梯、5409920A00 两步梯、7390202A 空心管）另出管材 STEP（单件/2026-10-22/make_tubes.py），
下料图里写长度与截面；板件、折弯件在此展开。
"""
import math
from ps20261020 import _views, _outline


def register(C):
    Q = 'Q235B'

    def main_plate(fname, w, h):
        for b in _views(C.DXF(fname)):
            if abs(b[2] - b[0] - w) < 0.05 and abs(b[3] - b[1] - h) < 0.05:
                return C.plate(fname, (b[0] - 0.5, b[1] - 0.5, b[2] + 0.5, b[3] + 0.5))
        raise ValueError('%s 中没有 %gx%g 的视图' % (fname, w, h))

    def flab(t, n):                       # 花纹板标签（同历史 NO.384 “花纹板,Q235B-4mm,1件” 写法）
        return '花纹板,' + C.lab(t, n, Q)

    # ---------------- NO.451 ----------------
    # 线槽支架 6mm：L 形，立边 55 + 横边 165（外形），宽 50，BD 10.5 → 209.5 × 50；两端角 R5；
    # 立边 8.5 宽腰孔（距端 24，横向 10~40）；横边 3-M8 距立边外表面 30 / 60 / 90。
    @C.part('1570950A')
    def _(q):
        t = 6; w = C.bd(t)
        rl = 55 - w / 2; L = rl + 165 - w / 2
        p = C.Piece().rect(0, 0, L, 50, 5)
        p.slot(24, 10, 24, 40, 8.5)
        for s in (30, 60, 90):
            p.tap(rl + s - w / 2, 25, 'M8')
        p.bend(rl, 0, rl, 50, w)
        return [(C.lab(t, q), p)]

    # 连接板 5mm：U 形，两立边 50 + 顶 153（外形），宽 60，BD 8.4 → 236.2 × 60，立边自由端角 R5；
    # 两立边各 2-M8 距底 20、横向 15 / 45；顶面 2-M8 距左外表面 36.5 / 116.5。
    @C.part('1574178A')
    def _(q):
        t = 5; w = C.bd(t)
        L = 50 + 153 + 50 - 2 * w
        r1, r2 = 50 - w / 2, L - 50 + w / 2
        p = C.Piece().rect(0, 0, L, 60, 5)
        for y in (15, 45):
            p.tap(20, y, 'M8').tap(L - 20, y, 'M8')
        for s in (36.5, 116.5):
            p.tap(r1 + s - w / 2, 30, 'M8')
        p.bend(r1, 0, r1, 60, w).bend(r2, 0, r2, 60, w)
        return [(C.lab(t, q), p)]

    # 连接板 5mm：L 形，立边 80 + 横边 200（外形），宽 60，BD 8.4 → 271.6 × 60，两端角 R5；
    # 立边 Φ14 距端 35；横边 2 条 8.5 宽腰孔，距立边外表面 119~189，横向 15 / 45。
    @C.part('1574179A')
    def _(q):
        t = 5; w = C.bd(t)
        rl = 80 - w / 2; L = rl + 200 - w / 2
        p = C.Piece().rect(0, 0, L, 60, 5)
        p.circle(35, 30, 14)
        for y in (15, 45):
            p.slot(rl + 119 - w / 2, y, rl + 189 - w / 2, y, 8.5)
        p.bend(rl, 0, rl, 60, w)
        return [(C.lab(t, q), p)]

    # 挡板 1mm：L 形，横边 120 + 折边 12（外形），宽 30，BD 1.7 → 130.3 × 30，四角 R2；表面喷黑
    @C.part('1574180A')
    def _(q):
        t = 1; w = C.bd(t)
        L = 120 + 12 - w
        p = C.Piece().rect(0, 0, L, 30, 2)
        p.bend(120 - w / 2, 0, 120 - w / 2, 30, w)
        return [(C.lab(t, q), p)]

    # ---------------- NO.461 ----------------
    # 一步梯（焊接件）：方管 40×40×1.5 Q235B（L400-45-45 ×2、L200-45-45 ×2、L300 ×4、L320 ×2、L120 ×2，见管材 STEP）
    # + A02 花纹板 400×200 R5 + A01 连接板 8mm 80×40 ×4
    @C.part('5363401A00')
    def _(q):
        out = [(C.lab(L, n * q, Q), C.tube_rect(40, 40, 1.5, 2.25))
               for L, n in ((400, 2), (200, 2), (300, 4), (320, 2), (120, 2))]
        out.append((flab(3, q), main_plate('5363401A00_图纸_3.dxf', 400, 200)))
        out.append((C.lab(8, 4 * q, Q), main_plate('5363401A00_图纸_2.dxf', 80, 40)))
        return out

    # 两步梯（焊接件）：方管 40×40×1.5 Q235B（L400-45-45 ×3、L300-45-45 ×2、L560-45 ×2、L532 ×2、L320 ×1、
    # L250 ×2、L242 ×2，见管材 STEP）+ 5363402A01 下踏板（带 25 折边）+ 5363402A02 上踏板 + 5363401A01 连接板 ×4
    @C.part('5409920A00')
    def _(q):
        out = [(C.lab(L, n * q, Q), C.tube_rect(40, 40, 1.5, 2.25))
               for L, n in ((400, 3), (300, 2), (560, 2), (532, 2), (320, 1), (250, 2), (242, 2))]
        # 5363402A01 花纹板 3mm：400 × 300 R10，y=300 边 x 40~360 下折 25（外形），两侧 3 × 7.5 释放口；BD 5
        t = 3; w = C.bd(t, Q)
        rl = 300 - w / 2; ye = rl + 25 - w / 2
        a01 = C.Piece().outline([(0, 0, 10), (400, 0, 10), (400, 300, 10), (363, 300), (363, 292.5), (360, 292.5),
                                 (360, ye), (40, ye), (40, 292.5), (37, 292.5), (37, 300), (0, 300, 10)])
        a01.bend(40, rl, 360, rl, w)
        out.append((flab(3, q), a01))
        out.append((flab(3, q), main_plate('5409920A00_图纸_4.dxf', 400, 300)))
        out.append((C.lab(8, 4 * q, Q), main_plate('5409920A00_图纸_2.dxf', 80, 40)))
        return out

    # 挡板 2mm Q235B：板 1460 × 740（R5），两长边各 4 个 120 宽耳片上折 50（外形，耳片外表面距 750），
    # 耳片顶角 R5、各一条 6.5 宽竖腰孔（距板底 12~42）；耳片之间板边退 5 作让位；BD 3.5。
    @C.part('5409919A')
    def _(q):
        t = 2; w = C.bd(t, Q)
        rl = w / 2                                   # 红线距耳片外表面 BD/2
        ye = rl - (50 - w / 2)                       # 耳片展开端（负向）
        tabs = (70, 360, 930, 1230)
        lo = [(0, 5, 5)]
        for x0 in tabs:
            lo += [(x0, 5), (x0, ye, 5), (x0 + 120, ye, 5), (x0 + 120, 5)]
        lo += [(1460, 5, 5), (1460, 745, 5)]
        for x0 in reversed(tabs):
            lo += [(x0 + 120, 745), (x0 + 120, 750 - ye, 5), (x0, 750 - ye, 5), (x0, 745)]
        lo += [(0, 745, 5)]
        p = C.Piece().outline(lo)
        for x0 in tabs:
            xc = x0 + 60
            p.slot(xc, w - 12, xc, w - 42, 6.5).slot(xc, 750 - w + 12, xc, 750 - w + 42, 6.5)
            p.bend(x0, rl, x0 + 120, rl, w).bend(x0, 750 - rl, x0 + 120, 750 - rl, w)
        return [(C.lab(t, q, Q), p)]

    # 连接件 3mm：L 形，立边 30 + 横边 110（外形），宽 40，BD 5 → 135 × 40，两端角 R5；横边 11 宽腰孔 15~95
    @C.part('5409922A')
    def _(q):
        t = 3; w = C.bd(t)
        rl = 30 - w / 2; L = rl + 110 - w / 2
        p = C.Piece().rect(0, 0, L, 40, 5)
        p.slot(rl + 15 - w / 2, 20, rl + 95 - w / 2, 20, 11)
        p.bend(rl, 0, rl, 40, w)
        return [(C.lab(t, q), p)]

    # ---------------- NO.462 ----------------
    # 空心管 Φ20×2 L1200（无图纸，按物料描述；管材 STEP 另出）
    C.part('7390202A-20×2-L=1200-SUS304')(lambda q: [(C.lab(1200, q), C.tube_round(20, 2))])

    # 光电支架 2mm（图纸标题栏零件号写 5407101A）：L 形，立边 51 + 底边 32（外形），宽 68，BD 3 → 80 × 68；
    # 立边顶角 R5、4 条 5 宽横腰孔（x 5.5~10.5 / 57.5~62.5，距顶 4 / 38）；
    # 底边梯形：两角 45° 切 10，切角处 R5，9 宽腰孔 x 11.5~56.5 距底边端 15.5。
    @C.part('7407101A')
    def _(q):
        t = 2; w = C.bd(t)
        rl = 51 - w / 2; L = rl + 32 - w / 2
        p = C.Piece()
        p.outline([(0, 0, 5), (68, 0, 5), (68, L - 10, 5), (58, L, 5), (10, L, 5), (0, L - 10, 5)])
        for u in (4, 38):
            p.slot(5.5, u, 10.5, u, 5).slot(57.5, u, 62.5, u, 5)
        p.slot(11.5, L - 15.5, 56.5, L - 15.5, 9)
        p.bend(0, rl, 68, rl, w)
        return [(C.lab(t, q), p)]

    # 反光板支架 2mm Q235B（BD 3.5）：U 形，长腿 30 + 顶 28 + 短腿 20（外形），展开 71；
    # 长腿 70 宽、下部 60° 收成底宽 40（R5），两条 90° 弧形孔（Φ25.4 中心距底 13，宽 3.5）；
    # 顶面开 50 宽窗口（R2）通到长腿折弯处；短腿两侧耳片到 85 宽（R5），两条 7 宽横腰孔（距底 8）。
    # 展开 v：长腿底 v=0 → 顶 → 短腿底 v=71；x 0~85（长腿、顶宽 x 7.5~77.5）。
    @C.part('7407104A')
    def _(q):
        t = 2; w = C.bd(t, Q)
        r1 = 30 - w / 2; r2 = r1 + 28 - w; L = r2 + 20 - w / 2      # 28.25 / 52.75 / 71
        sv = lambda y: 81 - y                                         # 短腿：前视图 y → 展开 v
        k = 12.89 / 22.34                                             # 60° 斜边：x 随 v 的变化率
        xb = 21.06 + 2.5 * k                                          # 斜边与底边交点 x（22.50）
        p = C.Piece()
        p.outline([(xb, 0, 5), (85 - xb, 0, 5), (77.5, 26, 5), (77.5, sv(26)), (85, sv(26), 5), (85, L, 5),
                   (0, L, 5), (0, sv(26), 5), (7.5, sv(26)), (7.5, 26, 5)])
        p.outline([(17.5, 26), (67.5, 26), (67.5, r1 - w / 2 + 16, 2), (17.5, r1 - w / 2 + 16, 2)])  # 窗口 v 26 ~ 42.5
        p.arc_slot(42.5, 13, 12.7, 135, 225, 3.5).arc_slot(42.5, 13, 12.7, -45, 45, 3.5)
        p.slot(8.75, sv(18), 18.75, sv(18), 7).slot(66.25, sv(18), 76.25, sv(18), 7)
        p.bend(7.5, r1, 17.5, r1, w).bend(67.5, r1, 77.5, r1, w)
        p.bend(7.5, r2, 77.5, r2, w)
        return [(C.lab(t, q, Q), p)]

    # 反光板支架 3mm：65 × 60 R5，2-Φ5.5、2-Φ4.5（取图纸实形）
    @C.part('7407105A')
    def _(q):
        return [(C.lab(3, q), main_plate('7407105A.dxf', 65, 60))]

    # 反光板支架 3mm：80 × 60 R5，2-Φ6.5、Φ3.5、80° 弧形孔 3.5 宽（取图纸实形）
    @C.part('7407106A')
    def _(q):
        return [(C.lab(3, q), main_plate('7407106A.dxf', 80, 60))]
