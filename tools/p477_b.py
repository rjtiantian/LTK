"""NO.477-NO.478 零件展开（第 B 批）：7420115A~7420119A、7420703A~7420741A 部分件。
外形尺寸法：展开长 = 各边外形之和 − 折弯数 × BD；面上特征距折弯外形交点 s → 红线 ± (s − BD/2)。"""
import math
from sheetlib import fillet_path, BEND


def register(C):
    Q = 'Q235B'

    def outline(p, verts):
        """同 Piece.outline，但去掉相邻两圆角相切时产生的零长线段（半圆端口用两个 r=w/2 圆角拼成）"""
        verts = [tuple(v) + (0.0,) * (3 - len(v)) for v in verts]
        pts = fillet_path(verts, True)
        out = []
        for i, pt in enumerate(pts):
            nx = pts[(i + 1) % len(pts)]
            if abs(pt[0] - nx[0]) < 1e-9 and abs(pt[1] - nx[1]) < 1e-9:
                continue
            out.append(pt)
        return p.poly(out, True)

    def bline(p, a, b, color):
        """单条折弯线（红=1 中心线 / 蓝=5 边界线），用于斜折弯线端点需落在轮廓上的场合"""
        attr = dict(linetype='CENTER', color=color)
        if color == 1:
            attr['ltscale'] = 0.5
        return p.poly([a, b], False, BEND, **attr)

    def arc_slot(p, cx, cy, R, w, a0, a1):
        """圆弧腰形孔：中心 (cx,cy)、中径 R、宽 w，从 a0° 到 a1°（逆时针）"""
        p.arc(cx, cy, R + w / 2, a0, a1).arc(cx, cy, R - w / 2, a0, a1)
        for a, s0 in ((a1, a1), (a0, a0 + 180)):
            ex, ey = cx + R * math.cos(math.radians(a)), cy + R * math.sin(math.radians(a))
            p.arc(ex, ey, w / 2, s0, s0 + 180)
        return p

