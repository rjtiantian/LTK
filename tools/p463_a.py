"""NO.463 钣金（2026-10-14 单）：1591001A~1591007A、5409916A。
1591001A~1591007A 历史 NO.463（2026-10-10）做过，按新图纸重新核对后建模（见 README）。"""


def register(C):
    @C.part('1591001A')                      # 螺母板 5mm 110x35 R10，4-M6
    def _(q):
        p = C.Piece().rect(0, 0, 110, 35, 10)
        for x in (25, 85):
            for y in (7.5, 27.5):
                p.tap(x, y, 'M6')
        return [(C.lab(5, q), p)]

    @C.part('1591003A')                      # 安装板 5mm 108x50 R10，4-Φ7
    def _(q):
        p = C.Piece().rect(0, 0, 108, 50, 10)
        for x in (24, 84):
            for y in (15, 35):
                p.circle(x, y, 7)
        return [(C.lab(5, q), p)]

    @C.part('1591004A')                      # 折弯杆 Φ10 圆钢：中心线 210 + R30 四分之一圆 + 30 + R30 四分之一圆 + 120
    def _(q):
        L = 210 + 30 + 120 + 2 * (C.math.pi / 2 * 30)            # 454.2
        return [(C.lab(round(L), q), C.Piece().circle(5, 5, 10, layer='0'))]

    # 光电支架 2mm L 形：竖边 45（外形）+ 底边 85（外形），BD 3 → 展开 127 x 80。
    # x 从竖边自由端起：红线 45 - 1.5 = 43.5；底边特征距竖边外表面 s → x = 42 + s；竖边特征距底边外表面 z → x = 45 - z。
    @C.part('1591005A')
    def _(q):
        t = 2; w = C.bd(t)                                    # 3
        p = C.Piece().outline([(0, 0, 5), (127, 0, 5), (127, 40, 5), (42 + 25, 80, 5), (0, 80, 5)])
        p.rect(41, 42, 57, 72)                               # 跨折弯窗口 30 高：底边到 s=15，竖边到 z=4
        p.circle(23, 46.5, 3.5)                              # 竖边转轴孔（距顶 23 → z=22）
        p.arc_slot(23, 46.5, 25.4, 67.5, 112.5, 3.5)         # 45° 弧形孔 R25.4 宽 3.5
        for y in (10, 30):
            p.slot(42 + 27.5, y, 42 + 71.5, y, 7)            # 腰孔 44 中心距，右端距外形 13.5
        p.bend(43.5, 0, 43.5, 42, w)
        p.bend(43.5, 72, 43.5, 80, w)
        return [(C.lab(t, q), p)]

    C.mirror('1591006A', '1591005A')         # 图纸参数表：对称制作

    @C.part('1591007A')                      # 反光板支架 2mm 100x100，斜切 (0,55)-(65,0)，全部 R5
    def _(q):
        p = C.Piece().outline([(0, 55, 5), (65, 0, 5), (100, 0, 5), (100, 100, 5), (0, 100, 5)])
        for x in (4, 56):
            for y in (62, 96):
                p.circle(x, y, 4.2)
        for x in (70, 90):
            p.slot(x, 13.5, x, 48.5, 7)
        return [(C.lab(2, q), p)]

    @C.part('5409916A')                      # 连接板 5mm 150x90 R10，2-Φ9 + 2 条 9 宽竖腰孔
    def _(q):
        p = C.Piece().rect(0, 0, 150, 90, 10)
        for x in (25, 125):
            p.circle(x, 10, 9)
            p.slot(x, 40, x, 80, 9)
        return [(C.lab(5, q), p)]
