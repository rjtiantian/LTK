"""NO.482 钣金2（客户 11-12 增补单）里新出 / 改了的 8 件：
1430321B、1610351A、1610353B00、1610624A、1611107A、1610626A、1610627A00、1610628A00。

外形尺寸法：展开长 = 各段外形和 − 折弯数 × BD；非 90° 折弯按 BD 表反算 K（同 p482_g / p482_h），只画红线。
1610351A 是 Φ20x3 圆管，管材 STEP 在 482/管材STEP/钣金2/。
"""
import os, sys, math
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))


def _K(t, R, w):
    """由 90° 的 BD 表反算 K"""
    return (2 * (R + t) - w) / (math.pi / 2) / t - R / t


def _ba(deg, t, R, K):
    """折弯区中性层弧长"""
    return math.radians(deg) * (R + K * t)


def register(C):
    # ================================================================== 1430321B 隔离开关支架 2.5mm
    @C.part('1430321B')
    def _(q):
        # 下翻边 22.5（外形）+ 立板 + 45° 偏折 20（两个 45° 折弯，内 R2.5）+ 上段，总高 152.5；宽 140。
        # 侧视图取段长：翻边直段 17.5、立板直段 86.465、斜段直段 25.18、上段直段 37.929；K 由 BD4 反算。
        # 两侧斜边在正视图里是一条直线（12.095°），斜段在正视图里被压缩，展开时按投影高度逐段换算 x。
        t = 2.5; R = 2.5; w = C.bd(t); K = _K(t, R, w)
        rn = R + K * t
        a90, a45 = _ba(90, t, R, K), _ba(45, t, R, K)
        s1 = 17.5 + a90                         # 立板直段起点（展开）
        s2 = s1 + 86.465                        # 第一个 45° 起
        s3 = s2 + a45                           # 斜段起
        s4 = s3 + 25.18                         # 第二个 45° 起
        s5 = s4 + a45                           # 上段起
        L = s5 + (153.131 - 115.202)            # 展开总长 179.07
        h3 = 92.096 + rn * math.sin(math.radians(45))       # 斜段起点中性层高度

        def h_of(s):                            # 展开坐标 → 侧视图高度（中性层）
            if s <= s2:
                return 5.631 + (s - s1)
            if s <= s3:
                th = (s - s2) / rn
                return 92.096 + rn * math.sin(th)
            if s <= s4:
                return h3 + (s - s3) * math.sin(math.radians(45))
            if s <= s5:
                th = math.radians(45) - (s - s4) / rn
                return 115.202 - rn * math.sin(th)
            return 115.202 + (s - s5)

        def s_of(h):                            # 立板 / 上段（真形）上的高度 → 展开
            return s1 + (h - 5.631) if h <= 92.096 else s5 + (h - 115.202)

        k = math.tan(math.radians(12.095))
        xl = lambda s: 0.11 + k * (h_of(s) - 0.63 - 83.019)     # 正视图 y = 侧视图高度 − 0.63
        sk = s_of(82.506 + 0.63)                # 竖边转斜边（R5）
        top = L
        # 缺口底：在斜段上（正视图 y 111.037 / 109.269 两面），取中间
        sb = s3 + ((111.037 + 109.269) / 2 + 0.63 - h3) / math.sin(math.radians(45))
        right = [(140 - xl(s), s, 0) for s in (s2, s3, s4, s5)]
        left = [(xl(s), s, 0) for s in (s5, s4, s3, s2)]
        xt = 0.11 + k * (152.5 - 83.019)        # 斜边到顶边 = 15.0
        # 翻边两角按「未注圆角 R5」（同 NO.465 老图）
        pts = [(0, 0, 5), (140, 0, 5), (140, sk, 5)] + right + [(140 - xt, top, 5), (102.5, top, 5), (102.5, sb, 5), (37.5, sb, 5),
                                                         (37.5, top, 5), (xt, top, 5)] + left + [(0, sk, 5)]
        p = C.Piece().outline(pts)
        yr1 = 22.5 - w / 2                      # 90° 红线 = 外形 22.5 − BD/2
        p.bend(0, yr1, 140, yr1, w)
        yb1 = s2 + a45 / 2; yb2 = s4 + a45 / 2
        p.bend(xl(yb1), yb1, 140 - xl(yb1), yb1, 0, red_only=True)
        p.bend(xl(yb2), yb2, 37.5, yb2, 0, red_only=True).bend(102.5, yb2, 140 - xl(yb2), yb2, 0, red_only=True)
        for x, y in ((70, 18), (70, 72), (6.5, 45), (133.5, 45)):      # 4-M4（正视图 y）
            p.tap(x, s_of(y + 0.63), 'M4')
        for x in (25, 115):                                              # 2-Φ11 通孔，距顶 15
            p.circle(x, s_of(137.5 + 0.63), 11)
        return [(C.lab(t, q), p)]

    # ================================================================== 1610351A 护栏支杆（管材）
    @C.part('1610351A')
    def _(q):
        return [(C.lab(370, q), C.tube_round(20, 3))]  # Φ20 / Φ14，长 370，两端 C1；STEP 在 管材STEP/钣金2

    # ================================================================== 1610353B00 导向板（焊接件：A01 ×1 + A02 ×2）
    @C.part('1610353B00')
    def _(q):
        # A01 导向板 3mm：立板 200 + 30° 折（内 R3）斜段 60 + 90° 折回 20（外形），宽 450，下两角 R10。
        t = 3; R = 3; w = C.bd(t); K = _K(t, R, w)
        L = 200 + 60 + 20 - w - (2 * (R + t) * math.tan(math.radians(15)) - _ba(30, t, R, K))   # 274.12
        y30 = 198.388 + _ba(30, t, R, K) / 2                # 30° 红线（立板直段 198.388 + 半个弧长）
        y90 = L - (20 - w / 2)                              # 90° 红线 = 外形 20 − BD/2
        a = C.Piece().outline([(0, 0, 10), (450, 0, 10), (450, L), (0, L)])
        a.bend(0, y30, 450, y30, 0, red_only=True).bend(0, y90, 450, y90, w)
        # A02 安装板 2.5mm U 形：22.5 + 35 + 22.5，长 150，展开 72；一条腿 2-Φ9（距腿边 8，中心距 100），腿端角 R5
        t2 = 2.5; w2 = C.bd(t2); W2 = 22.5 + 35 + 22.5 - 2 * w2
        b = C.Piece().outline([(0, 0, 5), (150, 0, 5), (150, W2, 5), (0, W2, 5)])
        r1 = 22.5 - w2 / 2
        b.bend(0, r1, 150, r1, w2).bend(0, W2 - r1, 150, W2 - r1, w2)
        b.circle(25, 8, 9).circle(125, 8, 9)
        return [(C.lab(t, q), a), (C.lab(t2, 2 * q), b)]

    # ================================================================== 1610624A 气缸安装板（底板 + 两侧板 + 背条）
    @C.part('1610624A')
    def _(q):
        # 5mm。11-12 新图侧板高 174 → 180（底板外宽 175、深 67.5、背条外形 40 不变），孔距顶 20 / 60 不变。
        # 做法同 638bcf4 旧定义，只换高度：展开 512.2 × 99.1
        t = 5; w = C.bd(t); H = 180
        WW = H + 175 + H - 2 * w
        rl = H - w / 2; rr = WW - rl
        ys = w / 2 - (40 - w / 2)                          # 背条自由边
        xh = lambda h: rl - (h - w / 2)                    # 侧板 / 背条：距底面 h → x
        xb = rl - (10 - w / 2)                             # 背条下端（h=10）
        xe = rl + (10 - w / 2)                             # 底板侧边（距外面 10）
        sl = xh(20)                                        # 斜边与前边交点（h=20）
        p = C.Piece().outline([(sl, 67.5, 5), (WW - sl, 67.5, 5), (WW, 20, 5), (WW, ys, 5), (WW - xb, ys), (WW - xb, 10),
                               (WW - xe, 10), (WW - xe, 0), (xe, 0), (xe, 10), (xb, 10), (xb, ys), (0, ys, 5), (0, 20, 5)])
        p.bend(rl, 10, rl, 67.5, w).bend(rr, 10, rr, 67.5, w)
        p.bend(0, w / 2, xb, w / 2, w).bend(WW - xb, w / 2, WW, w / 2, w)
        yb = w / 2 - (30 - w / 2)                          # 背条孔距外面 30
        for h in (H - 20, H - 60):                         # 4-Φ9 距顶 20 / 60
            p.circle(xh(h), yb, 9).circle(WW - xh(h), yb, 9)
        for s in (58, 117):                                # 2-M8 距前边 9，中心距 59
            p.tap(rl + s - w / 2, 67.5 - 9, 'M8')
        return [(C.lab(t, q), p)]

    # ================================================================== 1611107A 安装件
    @C.part('1611107A')
    def _(q):
        # 11-12 新图：5mm U 形 50 + 46 + 50（外形），宽 60，展开 129.2。
        # 两臂：上边直、R20 包 Φ12（距腹板外面 30、距上边 20），斜边切到下边、R5；腹板 2-M8（距下边 10 / 50）
        t = 5; w = C.bd(t)
        LL = 50 + 46 + 50 - 2 * w; r1 = 50 - w / 2; r2 = LL - r1
        # 臂视图斜边 (5.384, 26.349)-(28.516, 1.589)，延长到 y=0 / y=60
        m = (28.516 - 5.384) / (1.589 - 26.349)          # dx/dy
        x0 = 28.516 - m * 1.589; x60 = 28.516 + m * (60 - 1.589)
        p = C.Piece().outline([(x0, 0, 5), (LL - x0, 0, 5), (LL - x60, 60, 20), (x60, 60, 20)])
        p.bend(r1, 0, r1, 60, w).bend(r2, 0, r2, 60, w)
        p.circle(20, 40, 12).circle(LL - 20, 40, 12)
        p.tap(LL / 2, 10, 'M8').tap(LL / 2, 50, 'M8')
        return [(C.lab(t, q), p)]

    # ================================================================== 1610626A 反光板支架（图纸同 11-06 版，照搬 638bcf4 定义）
    @C.part('1610626A')
    def _(q):
        # 3mm L 形：翼板 25（x 0~130，自由段高 19）+ 支板 35（x 35~95），展开 55
        t = 3; w = C.bd(t)
        yr = 25 - w / 2; L = yr + 35 - w / 2
        p = C.Piece().outline([(0, 0, 5), (130, 0, 5), (130, 19, 5), (95, 19), (95, L, 5), (35, L, 5), (35, 19), (0, 19, 5)])
        p.bend(35, yr, 95, yr, w)
        p.slot(12.4, 10, 22.4, 10, 9).slot(107.6, 10, 117.6, 10, 9)
        yc = yr + 20 - w / 2
        p.circle(77.75, yc, 5.5)
        p.arc_slot(65, yc, 12.75, 150, 210, 5.5)
        return [(C.lab(t, q), p)]

    # ================================================================== 尾部封板 1610627A00 / 1610628A00（A01 3mm + 1570902A02 ×2）
    def fb(W, tab_left, slots, taps=()):
        """封板 3mm：下翻边 25 + 腹板 145 + 上翻边 19，一端耳板到 164，耳板与上翻边间 3.5 缺口到 h=125（同 p482_g fb）"""
        t = 3; w = C.bd(t)
        Yh = lambda h: 20 + h
        y2 = Yh(145) - w / 2; ytop = y2 + 19 - w / 2; ytab = Yh(164); yn = Yh(125)
        if tab_left:
            x0, x1 = 56.5, W
            pts = [(0, 0, 5), (W, 0, 5), (W, ytop, 5), (x0, ytop, 5), (x0, yn), (53, yn), (53, ytab, 5), (0, ytab, 5)]
        else:
            x0, x1 = 0, W - 56.5
            pts = [(0, 0, 5), (W, 0, 5), (W, ytab, 5), (W - 53, ytab, 5), (W - 53, yn), (x1, yn), (x1, ytop, 5), (0, ytop, 5)]
        p = C.Piece().outline(pts)
        p.bend(0, 25 - w / 2, W, 25 - w / 2, w).bend(x0, y2, x1, y2, w)
        for x0_, h0, x1_, h1 in slots:
            p.slot(x0_, Yh(h0), x1_, Yh(h1), 11)
        for x, h in taps:
            p.tap(x, Yh(h), 'M10')
        return p

    def nut_1570902():
        # 1570902A02 螺母板 5mm：85×20，C5 + R3，2-M8（6.647）；子件图在 1610607A00 图纸_3
        return C.plate('1610607A00.idw_图纸_3.dxf', (22, 55.3, 108, 76.3))

    @C.part('1610627A00')
    def _(q):
        # 长 600，耳板在右（上翻边 0~543.5）；竖腰孔 x140 h25~75、横腰孔 265~315 h50，宽 11；明细栏 A01 ×1 + 1570902A02 ×2
        p = fb(600, False, [(140, 25, 140, 75), (265, 50, 315, 50)])
        return [(C.lab(3, q), p), (C.lab(5, 2 * q), nut_1570902())]

    @C.part('1610628A00')
    def _(q):
        # 长 600，耳板在左（上翻边 56.5~600）；横腰孔 285~335 h50、竖腰孔 x460 h25~75，2-M10 x101.5 / 408.5 h88
        # 总图无明细栏，螺母板按视图 2 件（同 1610627A00 / 1610607A00）
        p = fb(600, True, [(285, 50, 335, 50), (460, 25, 460, 75)], taps=[(101.5, 88), (408.5, 88)])
        return [(C.lab(3, q), p), (C.lab(5, 2 * q), nut_1570902())]
