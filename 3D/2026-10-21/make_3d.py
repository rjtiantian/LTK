# -*- coding: utf-8 -*-
"""按二维图（DWG 矢量，474/DXF、475/DXF 同源）建 0181301A00 底座、1600111A00 支撑架三维模型。

用法（需 OCP）:  python3 3D/2026-10-21/make_3d.py  → 3D/2026-10-21/<物料号>_<名称>.step
坐标即二维图视图坐标（1:1）：
  0181301A00：主视图 x 0~960、y 0~840；侧视图 z 0~130（z=0 为脚板底面）
  1600111A00：主视图 x 0~2050、y 0~1110（y=0 为脚板底面）；俯视图 z 0~570（z=0 为前侧）
"""
import os, sys, math
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, '..', '..', 'tools'))
from frame3d import tube, plate, keep, cut, cyl, slot, prism, volume, bbox, valid, write_assembly

S2 = math.sqrt(0.5)
TAP = {'M8': 6.647, 'M16': 13.835, 'M20': 17.294}        # 螺纹孔按小径（同图纸里画的圆）


def base_0181301A00():
    P = []
    # 5 方管 AB 50×50×1-L840 ×2（外 R3、内 R2）
    lv = tube('y', (0, 0, 80), (50, 840, 130), 1, 3, 2)               # 左立：与上下横管在 xy 面 45° 斜接
    lv = keep(lv, (0, 0, 0), (-S2, S2, 0))                            # y ≥ x
    lv = keep(lv, (0, 840, 0), (-S2, -S2, 0))                         # x + y ≤ 840
    P.append(('方管50x50x1-L840 左立 (5)', lv))
    rv = tube('y', (910, 0, 80), (960, 840, 130), 1, 3, 2)            # 右立：与脚管在 yz 面 45° 斜接
    rv = keep(rv, (0, 0, 130), (0, S2, S2))                           # y + z ≥ 130
    rv = keep(rv, (0, 840, 130), (0, -S2, S2))                        # y − z ≤ 710
    P.append(('方管50x50x1-L840 右立 (5)', rv))
    # 4 方管 A 50×50×4-L910 ×2（外 R6、内 R2）：左端与左立斜接，右端平头顶右立
    hb = keep(tube('x', (0, 0, 80), (910, 50, 130), 4, 6, 2), (0, 0, 0), (S2, -S2, 0))      # x ≥ y
    ht = keep(tube('x', (0, 790, 80), (910, 840, 130), 4, 6, 2), (0, 840, 0), (S2, S2, 0))  # x + y ≥ 840
    P += [('方管50x50x4-L910 下 (4)', hb), ('方管50x50x4-L910 上 (4)', ht)]
    # 3 方管 A 50×50×1-L115 ×2：脚管 z 15~130，上端与右立斜接
    sb = keep(tube('z', (910, 0, 15), (960, 50, 130), 1, 3, 2), (0, 0, 130), (0, -S2, -S2))    # y + z ≤ 130
    st = keep(tube('z', (910, 790, 15), (960, 840, 130), 1, 3, 2), (0, 840, 130), (0, S2, -S2))  # y − z ≥ 710
    P += [('方管50x50x1-L115 下脚 (3)', sb), ('方管50x50x1-L115 上脚 (3)', st)]
    # 1 0120201A02 腿焊接02 ×2：15mm 50×50 R6，M20
    for nm, y0 in (('下', 0), ('上', 790)):
        P.append(('0120201A02 腿焊接02 %s (1)' % nm,
                  plate('z', (910, y0, 0), (960, y0 + 50, 15), 6, [(935, y0 + 25, TAP['M20'])])))
    # 2 0181301A01 横撑 ×2：4mm C 形，腹板 100（z 126~130，贴框架背面）、翼边 50（朝脚板侧），内 R4 外 R8，长 740
    for x0 in (200, 700):
        a, b = x0, x0 + 100
        k4, k8 = 4 * S2, 8 * S2
        sec = [('L', (a, 80), (a + 4, 80)), ('L', (a + 4, 80), (a + 4, 122)),
               ('A', (a + 4, 122), (a + 8 - k4, 122 + k4), (a + 8, 126)), ('L', (a + 8, 126), (b - 8, 126)),
               ('A', (b - 8, 126), (b - 8 + k4, 122 + k4), (b - 4, 122)), ('L', (b - 4, 122), (b - 4, 80)),
               ('L', (b - 4, 80), (b, 80)), ('L', (b, 80), (b, 122)),
               ('A', (b, 122), (b - 8 + k8, 122 + k8), (b - 8, 130)), ('L', (b - 8, 130), (a + 8, 130)),
               ('A', (a + 8, 130), (a + 8 - k8, 122 + k8), (a, 122)), ('L', (a, 122), (a, 80))]
        c = prism(sec, [], ('x', 'z'), 50, 740)          # 截面在 xz 面，沿 y 从 50 拉到 790
        for yc in (115, 375, 465, 725):                  # 腹板 4 条腰孔：宽 22，沿 x 中心距 35
            c = cut(c, slot('z', (x0 + 32.5, yc, 0), (x0 + 67.5, yc, 0), 22, 120, 135))
        P.append(('0181301A01 横撑 x%d (2)' % x0, c))
    return P


def stand_1600111A00():
    P = []
    T2 = dict(t=2, ro=3.75, ri=1.75)          # 50×50×2-R1.75（R 为内角）
    T15 = dict(t=1.5, ro=3.75, ri=2.25)       # 50×50×1.5-R2.25
    tb = lambda ax, lo, hi, s: tube(ax, lo, hi, s['t'], s['ro'], s['ri'])
    # 2 方管 50×50×1.5-L1100 ×2：后立柱（z 520~570，y 10~1110）
    for x0 in (0, 2000):
        P.append(('方管50x50x1.5-L1100 后立柱 x%d (2)' % x0, tb('y', (x0, 10, 520), (x0 + 50, 1110, 570), T15)))
    # 4 方管 L500 ×2：前腿（z 0~50，y 10~510）
    for x0 in (0, 2000):
        P.append(('方管50x50x2-L500 前腿 x%d (4)' % x0, tb('y', (x0, 10, 0), (x0 + 50, 510, 50), T2)))
    # 7 方管 L2050 ×1：上层前横（z 0~50，y 510~560），两端与上层侧横在 xz 面 45° 斜接；10-M8 中 5 个在此（z=15）
    f = tb('x', (0, 510, 0), (2050, 560, 50), T2)
    f = keep(f, (0, 0, 0), (S2, 0, -S2))                          # x ≥ z
    f = keep(f, (2050, 0, 0), (-S2, 0, -S2))                      # x + z ≤ 2050
    for x in (70, 570, 1070, 1570, 2020):
        f = cut(f, cyl('y', (x, 0, 15), TAP['M8'], 505, 565))
    P.append(('方管50x50x2-L2050 上前横 (7)', f))
    # 5 方管 L520 ×2：上层侧横（x 0~50 / 2000~2050，z 0~520），前端斜接、后端平头顶立柱
    l5 = keep(tb('z', (0, 510, 0), (50, 560, 520), T2), (0, 0, 0), (-S2, 0, S2))           # z ≥ x
    r5 = keep(tb('z', (2000, 510, 0), (2050, 560, 520), T2), (2050, 0, 0), (S2, 0, S2))    # x + z ≥ 2050
    r5 = cut(r5, cyl('y', (2020, 0, 300), TAP['M8'], 505, 565))                             # 10-M8 之一
    P += [('方管50x50x2-L520 上左侧横 (5)', l5), ('方管50x50x2-L520 上右侧横 (5)', r5)]
    # 6 方管 L1950 ×4：上后横（z 520~570）、上中横（z 265~315，4-M8 于 z=300）、下后横（z 520~570）、下中横（z 250~300）
    P.append(('方管50x50x2-L1950 上后横 (6)', tb('x', (50, 510, 520), (2000, 560, 570), T2)))
    m = tb('x', (50, 510, 265), (2000, 560, 315), T2)
    for x in (70, 570, 1070, 1570):
        m = cut(m, cyl('y', (x, 0, 300), TAP['M8'], 505, 565))
    P.append(('方管50x50x2-L1950 上中横 (6)', m))
    P.append(('方管50x50x2-L1950 下后横 (6)', tb('x', (50, 160, 520), (2000, 210, 570), T2)))
    P.append(('方管50x50x2-L1950 下中横 (6)', tb('x', (50, 160, 250), (2000, 210, 300), T2)))
    # 3 方管 L470 ×2：下层侧横（z 50~520，y 160~210）
    for x0 in (0, 2000):
        P.append(('方管50x50x2-L470 下侧横 x%d (3)' % x0, tb('z', (x0, 160, 50), (x0 + 50, 210, 520), T2)))
    # 1 1450230A01 脚蹄固定板 ×4：10mm 50×50 R3，M16
    for x0 in (0, 2000):
        for z0 in (0, 520):
            P.append(('1450230A01 脚蹄固定板 x%d z%d (1)' % (x0, z0),
                      plate('y', (x0, 0, z0), (x0 + 50, 10, z0 + 50), 3, [(x0 + 25, z0 + 25, TAP['M16'])])))
    return P


if __name__ == '__main__':
    for code, name, fn in (('0181301A00', '底座', base_0181301A00), ('1600111A00', '支撑架', stand_1600111A00)):
        parts = fn()
        tot = 0
        for nm, s in parts:
            v = volume(s); tot += v
            print('  %-34s 体积 %9.0f  %s  %s' % (nm, v, bbox(s), '' if valid(s) else '!!! 实体无效'))
        out = os.path.join(HERE, '%s_%s.step' % (code, name))
        write_assembly(parts, out, '%s %s' % (code, name))
        print('%s %s：%d 件，总质量 %.2f kg（7.93） → %s' % (code, name, len(parts), tot * 7.93e-6, out))
